// 2. TRANSLATION ENGINE
// ---------------------------------------------------------------------------

/**
 * Build sorted phrase keys for longest-match-first searching.
 */
const PHRASE_KEYS = Object.keys(PHRASE_DICT).sort((a, b) => b.length - a.length);

/**
 * Remove USDA artefacts like "NFS", "NS as to ..." etc.
 */
function cleanUsdaArtefacts(text) {
  // Remove "NFS" and variants
  text = text.replace(/\bNFS\b/gi, '');
  text = text.replace(/\bN\.F\.S\.\b/gi, '');
  // Remove "NS as to ..." clauses
  text = text.replace(/\bNS\s+as\s+to\s+[^,)]*/gi, '');
  // Remove "not further specified"
  text = text.replace(/\bnot\s+further\s+specified\b/gi, '');
  // Remove "not specified"
  text = text.replace(/\bnot\s+specified\b/gi, '');
  // Clean up leftover commas / extra spaces
  text = text.replace(/,\s*,/g, ',');
  text = text.replace(/,\s*$/g, '');
  text = text.replace(/^\s*,/g, '');
  text = text.replace(/\s{2,}/g, ' ');
  return text.trim();
}

/**
 * Translate a USDA food name to Polish.
 *
 * Strategy:
 * 1. Clean USDA artefacts
 * 2. Split on commas into segments
 * 3. For each segment, try longest-phrase-first matching
 * 4. Fall back to single-word dictionary
 * 5. Reassemble with commas
 */
function translateName(nameEn) {
  let cleaned = cleanUsdaArtefacts(nameEn);

  // Split by commas, preserving structure
  const segments = cleaned.split(',').map(s => s.trim()).filter(Boolean);

  const translatedSegments = segments.map(seg => translateSegment(seg));

  return translatedSegments.join(', ');
}

function translateSegment(segment) {
  let lower = segment.toLowerCase().trim();
  let result = lower;

  // Phase 1: Try whole-segment phrase match first
  if (PHRASE_DICT[lower]) {
    return PHRASE_DICT[lower];
  }

  // Phase 2: Replace phrases (longest first) within the segment
  let working = ' ' + lower + ' '; // pad for word-boundary matching
  for (const phrase of PHRASE_KEYS) {
    const escaped = phrase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const regex = new RegExp('(?<=\\s|^)' + escaped + '(?=\\s|$)', 'gi');
    if (regex.test(working)) {
      working = working.replace(regex, '{{PH_' + phrase + '}}');
    }
  }

  // Phase 3: Replace remaining single words
  const tokens = working.trim().split(/\s+/);
  const translated = tokens.map(token => {
    // Check if it's a placeholder
    const phMatch = token.match(/^\{\{PH_(.+)\}\}$/);
    if (phMatch) {
      return PHRASE_DICT[phMatch[1]];
    }

    // Handle parenthetical content
    const parenMatch = token.match(/^\((.+)\)$/);
    if (parenMatch) {
      const inner = translateWord(parenMatch[1]);
      return '(' + inner + ')';
    }

    return translateWord(token);
  });

  return translated.join(' ');
}

function translateWord(word) {
  const lower = word.toLowerCase().replace(/[()]/g, '');
  if (!lower) return word;

  // Direct dictionary hit
  if (WORD_DICT[lower]) {
    return WORD_DICT[lower];
  }

  // Try without trailing 's' for plural
  if (lower.endsWith('s') && WORD_DICT[lower.slice(0, -1)]) {
    return WORD_DICT[lower.slice(0, -1)];
  }

  // Try without trailing 'es'
  if (lower.endsWith('es') && WORD_DICT[lower.slice(0, -2)]) {
    return WORD_DICT[lower.slice(0, -2)];
  }

  // Try without trailing 'ed' → past participle
  if (lower.endsWith('ed')) {
    const stem = lower.slice(0, -2);
    if (WORD_DICT[stem]) return WORD_DICT[stem];
    const stem2 = lower.slice(0, -1); // e.g., "baked" → "bake"
    if (WORD_DICT[stem2]) return WORD_DICT[stem2];
  }

  // Numbers, percentages, units — keep as-is
  if (/^\d+[\d.%]*$/.test(lower)) return word;

  // Keep unrecognized word as-is (brand name / foreign / already Polish)
  return word;
}

