/**
 * Polish diacritics → ASCII mapping
 */
const DIACRITICS_MAP = {
  'ą': 'a', 'ć': 'c', 'ę': 'e', 'ł': 'l', 'ń': 'n',
  'ó': 'o', 'ś': 's', 'ź': 'z', 'ż': 'z',
  'Ą': 'a', 'Ć': 'c', 'Ę': 'e', 'Ł': 'l', 'Ń': 'n',
  'Ó': 'o', 'Ś': 's', 'Ź': 'z', 'Ż': 'z',
  'à': 'a', 'á': 'a', 'â': 'a', 'ã': 'a', 'ä': 'a', 'å': 'a',
  'è': 'e', 'é': 'e', 'ê': 'e', 'ë': 'e',
  'ì': 'i', 'í': 'i', 'î': 'i', 'ï': 'i',
  'ò': 'o', 'ô': 'o', 'õ': 'o', 'ö': 'o',
  'ù': 'u', 'ú': 'u', 'û': 'u', 'ü': 'u',
  'ý': 'y', 'ÿ': 'y', 'ñ': 'n', 'ð': 'd', 'þ': 'th',
  'ß': 'ss', 'æ': 'ae', 'œ': 'oe', 'ø': 'o',
  'č': 'c', 'ď': 'd', 'ě': 'e', 'ň': 'n', 'ř': 'r', 'š': 's',
  'ť': 't', 'ů': 'u', 'ž': 'z',
};

function removeDiacritics(str) {
  return str.split('').map(ch => DIACRITICS_MAP[ch] || ch).join('');
}

function generateSlug(polishName) {
  let slug = polishName.toLowerCase();
  slug = removeDiacritics(slug);
  // Remove (a) gender markers from adjectives
  slug = slug.replace(/\(a\)/g, '');
  // Replace commas, spaces, underscores, slashes with hyphens
  slug = slug.replace(/[,\s_/\\]+/g, '-');
  // Remove all non-alphanumeric except hyphens
  slug = slug.replace(/[^a-z0-9-]/g, '');
  // Collapse multiple hyphens
  slug = slug.replace(/-{2,}/g, '-');
  // Trim leading/trailing hyphens
  slug = slug.replace(/^-+|-+$/g, '');
  // Limit length
  if (slug.length > 200) slug = slug.substring(0, 200).replace(/-+$/, '');
  return slug;
}

