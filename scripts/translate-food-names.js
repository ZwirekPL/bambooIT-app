async function main() {
  const ROOT = path.resolve(__dirname, '..');
  const INPUT_FILE = path.join(ROOT, 'food-names-to-translate.json');
  const OUTPUT_FILE = path.join(ROOT, 'food-names-translated.json');

  // --- Load input ---
  console.log('=== USDA Food Name Translator (EN → PL) ===');
  console.log(`Reading input from: ${INPUT_FILE}`);

  if (!fs.existsSync(INPUT_FILE)) {
    console.error(`ERROR: Input file not found: ${INPUT_FILE}`);
    console.error('Expected format: [{ "id": "...", "nameEn": "..." }, ...]');
    process.exit(1);
  }

  const raw = fs.readFileSync(INPUT_FILE, 'utf-8');
  const items = JSON.parse(raw);

  if (!Array.isArray(items) || items.length === 0) {
    console.error('ERROR: Input file must contain a non-empty JSON array.');
    process.exit(1);
  }

  console.log(`Loaded ${items.length} items to translate.\n`);

  // --- Translate ---
  const results = [];
  let translated = 0;
  let unchanged = 0;

  for (const item of items) {
    const { id, nameEn } = item;
    if (!id || !nameEn) {
      console.warn(`WARN: Skipping item with missing id or nameEn:`, item);
      continue;
    }

    const namePl = translateName(nameEn);
    const slug = generateSlug(namePl);
    const changed = namePl.toLowerCase() !== nameEn.toLowerCase();

    results.push({
      id,
      nameEn,
      namePl,
      slug,
      changed,
    });

    if (changed) translated++;
    else unchanged++;

    // Progress every 500 items
    if (results.length % 500 === 0) {
      console.log(`  ... processed ${results.length}/${items.length}`);
    }
  }

  console.log(`\nTranslation complete:`);
  console.log(`  Total:      ${results.length}`);
  console.log(`  Translated: ${translated}`);
  console.log(`  Unchanged:  ${unchanged}`);

  // --- Save translated file for review ---
  console.log(`\nSaving translations to: ${OUTPUT_FILE}`);
  fs.writeFileSync(OUTPUT_FILE, JSON.stringify(results, null, 2), 'utf-8');
  console.log('Saved.\n');

  // --- Update database ---
  console.log('Connecting to database...');

  const prisma = new PrismaClient({
    datasources: {
      db: {
        url: process.env.DATABASE_URL || 'postgresql://dietetyk:dietetyk123@localhost:5432/dietetyk_ai?schema=public',
      },
    },
  });

  try {
    // Test connection
    await prisma.$queryRaw`SELECT 1`;
    console.log('Database connected.\n');

    const BATCH_SIZE = 100;
    const totalBatches = Math.ceil(results.length / BATCH_SIZE);
    let updatedCount = 0;
    let errorCount = 0;

    for (let i = 0; i < results.length; i += BATCH_SIZE) {
      const batch = results.slice(i, i + BATCH_SIZE);
      const batchNum = Math.floor(i / BATCH_SIZE) + 1;

      const promises = batch.map(async (item) => {
        try {
          await prisma.foodProduct.update({
            where: { id: item.id },
            data: {
              name: item.namePl,
              nameEn: item.nameEn,
              languageCode: 'pl',
              slug: item.slug,
            },
          });
          updatedCount++;
        } catch (err) {
          // Handle unique slug constraint — append id suffix
          if (err.code === 'P2002' && err.meta?.target?.includes('slug')) {
            try {
              const uniqueSlug = item.slug + '-' + item.id.slice(-6);
              await prisma.foodProduct.update({
                where: { id: item.id },
                data: {
                  name: item.namePl,
                  nameEn: item.nameEn,
                  languageCode: 'pl',
                  slug: uniqueSlug,
                },
              });
              updatedCount++;
              console.warn(`  WARN: Duplicate slug for "${item.nameEn}" → used "${uniqueSlug}"`);
            } catch (retryErr) {
              errorCount++;
              console.error(`  ERROR updating id=${item.id} ("${item.nameEn}"): ${retryErr.message}`);
            }
          } else {
            errorCount++;
            console.error(`  ERROR updating id=${item.id} ("${item.nameEn}"): ${err.message}`);
          }
        }
      });

      await Promise.all(promises);

      if (batchNum % 5 === 0 || batchNum === totalBatches) {
        console.log(`  Batch ${batchNum}/${totalBatches} done (${updatedCount} updated, ${errorCount} errors)`);
      }
    }

    console.log(`\n=== Database update complete ===`);
    console.log(`  Updated: ${updatedCount}`);
    console.log(`  Errors:  ${errorCount}`);
  } catch (err) {
    console.error('Database error:', err.message);
    process.exit(1);
  } finally {
    await prisma['$disconnect']();
    console.log('Database disconnected.');
  }

  console.log('\nDone!');
}

main().catch((err) => {
  console.error('Fatal error:', err);
  process.exit(1);
});
